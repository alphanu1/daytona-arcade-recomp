"""Actual name catalog -> DNM2 -> native reader; requires owned ROM images.

Usage: python3 test_name_models.py SOURCE_DIR ROM_IMAGES check_native_meshpack
"""
from pathlib import Path
import json
import struct
import subprocess
import sys
import tempfile

tools = Path(__file__).resolve().parents[1] / 'tools'
sys.path.insert(0, str(tools))
import prepare_models as models

source, images, reader = map(Path, sys.argv[1:])
program, main = models.car_images(images)
# Independent halfword read of the original unaligned selection table.
addresses = []
for i in range(29):
    lo, hi = struct.unpack_from('<HH', program, 0x3b8f6 + 32*i)
    addresses.append(struct.unpack_from('<I', main, (lo | hi << 16) - 0x2000000)[0])
addresses.append(struct.unpack_from('<I', main, 0x88ac90)[0])

with tempfile.TemporaryDirectory() as directory:
    pack = Path(directory) / 'name.dnm'
    header = Path(directory) / 'name_data.h'
    exported = subprocess.run([sys.executable, str(tools / 'prepare_models.py'), str(source),
                    str(pack), '--name-models', str(images), '--share-positions',
                    '--name-header',str(header)],
                   check=True, capture_output=True, text=True)
    report = json.loads(exported.stdout)
    #5418's shared 3D palette is NOT part of the static label palette export.
    assert len(report['name_solid_palette']) == 2
    assert {tuple(r['header']) for r in report['name_solid_palette']} == {
        (0,0,0,2240), (0,0,0,10496)}
    for row in report['name_solid_palette']:
        offset = 0x8955a0+2*((row['header'][3]>>6)&1023)
        assert row['raw_color'] == int.from_bytes(main[offset:offset+2], 'little')
        assert len(row['argb_by_display_mode']) == 2
        assert all(len(colors)==64 for colors in row['argb_by_display_mode'])
    # Existing source-renderer samples, not colours generated by this packer.
    palettes = {tuple(r['header']): r['argb_by_display_mode'][0]
                for r in report['name_solid_palette']}
    seen = set()
    for line in models.rows(source/'material_lights.txt'):
        h0,h1,h2,h3,luma,argb = map(int,line)
        key = (h0,h1,h2,h3)
        assert palettes[key][luma>>2] == argb
        seen.add((key,luma))
    assert len(seen) == 512
    layout = report['name_layout']
    def source_float(at):
        lo, hi = struct.unpack_from('<HH', program, at)
        return struct.unpack('<f', struct.pack('<I', lo | hi << 16))[0]
    assert layout['initial_x'] == [source_float(0x3b8e2+4*i) for i in range(3)]
    assert len(layout['ring']) == 29
    for i, row in enumerate(layout['ring']):
        at = 0x3b8f2+32*i
        angle = int.from_bytes(program[at+24:at+26], 'little', signed=True)
        assert row == dict(radius=source_float(at), angle=angle,
            exit_velocity=[source_float(at+8+4*j) for j in range(3)],
            exit_scale=source_float(at+20),
            exit_spin=[int.from_bytes(program[at+26+2*j:at+28+2*j], 'little', signed=True) for j in range(3)])
    subprocess.run([str(reader.resolve()), str(pack)], check=True)
    data = pack.read_bytes()
    assert report['bytes'] == len(data)
    h = models.HEADER.unpack_from(data)
    assert h[0] == 0x324d4e44 and h[2] == h[6] == 30
    at = (models.HEADER.size + h[2]*models.MESH.size + h[3]*models.VERTEX.size
          + h[4]*models.FACE.size + h[5]*models.MATERIAL.size)
    for i, address in enumerate(addresses):
        instance = models.INSTANCE.unpack_from(data, at + i*models.INSTANCE.size)
        assert instance[:4] == (i, address, 0, 0)
        assert instance[4:16] == (1,0,0,0,1,0,0,0,1,0,0,0)
    assert h[8:12] == (0,0,0,0)
    # Compile the actual generated C constants and read their representations.
    probe=Path(directory)/'probe.c'
    probe.write_text('''#include <stdio.h>
#include "name_data.h"
int main(void) {
    fwrite(nm_name_layout_data.radius,4,29,stdout);
    fwrite(nm_name_layout_data.initial_x,4,3,stdout);
    fwrite(nm_name_layout_data.angle,2,29,stdout);
    for(unsigned i=0;i<29;++i) {
        const nm_name_exit_t *e=nm_name_layout_data.exit+i;
        if((uintptr_t)e%32) return 1;
        fwrite(e->velocity,4,3,stdout);fwrite(&e->scale_rate,4,1,stdout);
        fwrite(e->spin,2,3,stdout);
    }
    fwrite(nm_name_colors,1,sizeof(nm_name_colors),stdout);
    fwrite(nm_name_material_headers,1,sizeof(nm_name_material_headers),stdout);
    fwrite(nm_name_model_addresses,1,sizeof(nm_name_model_addresses),stdout);
    return ferror(stdout)!=0;
}
''')
    binary=Path(directory)/'probe'
    subprocess.run(['cc','-std=c11','-I',str(tools.parent/'include'),str(probe),
                    '-o',str(binary)],check=True)
    actual=subprocess.check_output([str(binary)])
    expected=struct.pack('=32f29h',*[r['radius'] for r in layout['ring']],
        *layout['initial_x'],*[r['angle'] for r in layout['ring']])
    for row in layout['ring']:
        expected+=struct.pack('=4f3h',*row['exit_velocity'],row['exit_scale'],*row['exit_spin'])
    expected+=struct.pack('=256I',*[c for m in report['name_solid_palette']
        for colors in m['argb_by_display_mode'] for c in colors])
    expected+=struct.pack('=8H',*[h for m in report['name_solid_palette'] for h in m['header']])
    expected+=struct.pack('=30I',*addresses)
    assert actual==expected
    preserved=header.read_bytes()
    rejected=subprocess.run([sys.executable,str(tools/'prepare_models.py'),str(source),
        str(Path(directory)/'other.dnm'),'--name-models',str(images),'--name-header',str(header)],
        capture_output=True)
    assert rejected.returncode and not (Path(directory)/'other.dnm').exists()
    assert header.read_bytes()==preserved
print('PASS: 29 name glyphs plus marker, ROM layout/shared solid palette, identity poses, native DNM2 reader')
