#!/bin/sh
# The Dreamcast build's game options (platform/dreamcast-native/local.cfg.mk
# defaults, -D flags) for the PC build, as a CMake list.
#
#   sh capture_flags.sh ASSET_OUTDIR OUT.cmake
#
# ASSET_OUTDIR is build_assets.sh's output (its make-vars.txt names the
# generated header directories the options depend on).
set -eu
OUT_DIR=$1
OUT=$2
HERE=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd -P)
DN=$(CDPATH= cd -- "$HERE/../../dreamcast-native" && pwd -P)
VARS=$(grep -v '^#' "$OUT_DIR/make-vars.txt" | tr '\n' ' ')
PRINT=$(mktemp)
trap 'rm -f "$PRINT"' EXIT
printf 'pc-print-flags: ; $(info $(DEFINES)) $(info $(ENJ_CFLAGS)) @:\n' > "$PRINT"
# shellcheck disable=SC2086
# NATIVE_SH4ZAM_ROOT= : no SH4 library check (the PC build compiles SH4ZAM's portable back end).
RAW=$(make -s -C "$DN" -f Makefile -f "$PRINT" ENJ_TARGET=pc-endjinn NATIVE_SH4ZAM_ROOT= $VARS pc-print-flags) || {
  echo "capture_flags.sh: make could not evaluate the Dreamcast build's options" >&2
  exit 1
}
printf '%s\n' "$RAW" | python3 -c '
import shlex, sys
keep = []
drop_prefix = ("NM_ASSET_ROOT", "ENJ_CBASEPATH", "_arch_", "__DREAMCAST__", "__SH4", "FRAME_POINTERS")
for token in shlex.split(sys.stdin.read()):
    if not token.startswith("-D"):
        continue
    d = token[2:]
    if d.startswith(drop_prefix) or d in keep:
        continue
    keep.append(d)
out = open(sys.argv[1], "w")
out.write("# Generated by platform/pc-native/recipes/capture_flags.sh\nset(DAYTONA_GAME_DEFINES\n")
for d in keep:
    out.write("  \"%s\"\n" % d.replace("\\", "\\\\").replace("\"", "\\\""))
out.write(")\n")
print("%d game options -> %s" % (len(keep), sys.argv[1]))
' "$OUT"
