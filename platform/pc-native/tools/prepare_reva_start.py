#!/usr/bin/env python3
"""Revision A's rolling-start camera for the PC build, from your own `daytona` ROM set.

    python3 prepare_reva_start.py daytona.zip OUT.h [--check-program IMPORTED_PROGRAM.bin]

Revision A (1994) films its race start around the player's car; Deluxe '93 (the set the port is built
from) anchors the same Beginner keys to opponents until the countdown. The camera is data in the program
and main data ROMs:

  program 0x63d8..0x6420   case of the camera selector, as Deluxe '93's 5b88: ld 6c98[501460*4] -> 50149c
                           (course slot 0 Beginner, 1 Expert, 2 Advanced; linked cabinets other than car 1
                           take 6ca8 on the Beginner by 540027, not used here)
  program 0x6c98           three pointers into main data, one per course slot
  main data, each record   64 bytes: +0 time (ticks), +4 cabinet mask (a record is skipped while bit
                           [501752] is set; zero in every start record), +8 eye car (-1: world), +c eye,
                           +18 target car, +1c target, +28 roll, +2c field of view (degrees; x 65536/360
                           -> 501744), +30 / +34 a projection alternative unused here (zero mode); a
                           record whose time is -1 links on (the start is never long enough to reach it).
  updater 0x65b4           the same linear blend between keys as Deluxe '93's 5cac, anchors through 6a10;
  focus 0x6f38..0x6fac     501734 = 248 / tan(half the field of view), the focus word Deluxe '93 keys hold.

Writes nm_reva_start_keys[4][] / nm_reva_start_times[4][] / nm_reva_start_counts[4] in the native key type
(include/intro_math.h nm_intro_key_t). ROM-derived: keep OUT.h under build/.
"""
import math
import struct
import sys
import zipfile
import zlib

PROGRAM = [("epr-16722a.12", 0x48B94318, 0), ("epr-16723a.13", 0x8AF8B32D, 2)]   # 16-bit interleave
MAIN_HIGH = [("epr-16724a.6", 0x469F10FD, 0), ("epr-16725a.7", 0xBA0DF8DB, 2)]   # main data 0x800000..
MAIN_BASE = 0x2000000
START_TABLE = 0x6C98            # program address of the per-course pointers
FOCUS_HALF_WIDTH = 248.0        # program 0x230b8c
ANGLE_SCALE = 182.04            # program 0x230b94, the float as stored (182.0399932861328)


def interleave(parts):
    """Two EPROMs loaded at +0 and +2 (ROM_LOAD16_WORD pairs): 16-bit words alternate."""
    size = len(parts[0][1])
    out = bytearray(size * 2)
    lo, hi = parts[0][1], parts[1][1]
    for i in range(0, size, 2):
        out[2 * i:2 * i + 2] = lo[i:i + 2]
        out[2 * i + 2:2 * i + 4] = hi[i:i + 2]
    return bytes(out)


def load(z, members):
    names = {n.rsplit('/', 1)[-1]: n for n in z.namelist()}
    parts = []
    for name, crc, offset in members:
        if name not in names:
            sys.exit(f"{name} missing: this needs MAME's daytona (Revision A) set")
        data = z.read(names[name])
        if zlib.crc32(data) != crc:
            sys.exit(f"{name}: CRC-32 {zlib.crc32(data):08x}, expected {crc:08x}")
        parts.append((offset, data))
    return interleave(sorted(parts))


def f32(value):
    return struct.unpack('<f', struct.pack('<f', value))[0]


def c_float(value):
    return '0x0.0p+0f' if value == 0 else f'{float.hex(value)}f'


def main():
    args = sys.argv[1:]
    if len(args) not in (2, 4):
        sys.exit(__doc__)
    with zipfile.ZipFile(args[0]) as z:
        program = load(z, PROGRAM)
        main_high = load(z, MAIN_HIGH)
    if len(args) == 4 and args[2] == '--check-program':
        imported = open(args[3], 'rb').read()
        if imported[:len(program)] != program:
            sys.exit("program image differs from the importer's")
    def program_word(address):
        return struct.unpack_from('<I', program, address)[0]
    def main_record(address):
        offset = address - MAIN_BASE - 0x800000
        if not 0 <= offset <= len(main_high) - 64:
            sys.exit(f"camera record {address:08x} outside main data 0x800000..")
        return struct.unpack_from('<16I', main_high, offset), struct.unpack_from('<16f', main_high, offset)
    # The selector case 63d8: lda 0x6c98,r5 (opcode 8c283000) must be where Revision A has it.
    if struct.unpack_from('<2I', program, 0x63E4) != (0x8C283000, START_TABLE):
        sys.exit("program 63e4 is not the start-camera selector of Revision A")
    out = ['/* Generated by platform/pc-native/tools/prepare_reva_start.py from your daytona (Revision A) set.',
           ' * ROM-derived: do not distribute. Revision A\'s race-start camera, by course slot 501460. */',
           '#ifndef DAYTONA_PC_RACE_START_REVA_H', '#define DAYTONA_PC_RACE_START_REVA_H', '#include "intro_math.h"',
           '#define NM_HAVE_REVA_START 1']
    keys_out, times_out, counts = [], [], []
    for view in range(3):
        address = program_word(START_TABLE + 4 * view)
        keys, times = [], []
        while len(keys) < 32:
            w, f = main_record(address)
            if w[0] == 0xFFFFFFFF:
                break
            if w[1] != 0:
                sys.exit(f"course {view}: record {address:08x} has cabinet mask {w[1]:x}")
            if w[13] != 0:
                sys.exit(f"course {view}: record {address:08x} uses projection mode {w[13]}")
            anchor = lambda word: -1 if word == 0xFFFFFFFF else word
            if anchor(w[2]) > 43 or anchor(w[6]) > 43:
                sys.exit(f"course {view}: record {address:08x} anchors outside the field")
            angle = int(round(f32(f[11] * f32(ANGLE_SCALE))))          # cvtri -> 501744 (int16)
            half = (angle & 0xFFFF) >> 1                                  # shri 1 (non-negative fields)
            radians = half * (2.0 * math.pi / 65536.0)
            focus = f32(FOCUS_HALF_WIDTH * math.cos(radians) / math.sin(radians))
            keys.append('{%d,%d,{%s},{%s},%s,%s}' % (
                anchor(w[2]), anchor(w[6]), ','.join(c_float(x) for x in f[3:6]),
                ','.join(c_float(x) for x in f[7:10]), c_float(f[10]), c_float(focus)))
            times.append(w[0])
            address += 64
        if len(keys) < 2 or times[0] != 0 or any(b <= a for a, b in zip(times, times[1:])):
            sys.exit(f"course {view}: unexpected key times {times}")
        keys_out.append(keys)
        times_out.append(times)
        counts.append(len(keys))
    n = max(counts)
    pad_key = lambda ks: ks + [ks[-1]] * (n - len(ks))
    pad_time = lambda ts: ts + [ts[-1]] * (n - len(ts))
    out.append(f'enum {{ NM_REVA_START_KEYS_MAX = {n} }};')
    out.append('static const alignas(32) nm_intro_key_t nm_reva_start_keys[3][NM_REVA_START_KEYS_MAX] = {')
    out.append(',\n'.join('{' + ',\n '.join(pad_key(k)) + '}' for k in keys_out) + '};')
    out.append('static const alignas(32) uint32_t nm_reva_start_times[3][NM_REVA_START_KEYS_MAX] = {')
    out.append(',\n'.join('{' + ','.join(map(str, pad_time(t))) + '}' for t in times_out) + '};')
    out.append('static const unsigned nm_reva_start_counts[3] = {' + ','.join(map(str, counts)) + '};')
    out += ['#endif', '']
    with open(args[1], 'w') as fh:
        fh.write('\n'.join(out))
    print(f"Revision A start camera: views {counts} keys -> {args[1]}")


if __name__ == '__main__':
    main()
